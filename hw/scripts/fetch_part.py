"""Fetch a JLCPCB/LCSC part (symbol, footprint, 3D model) into hw/parts/ without an atopile login.

Usage:  uv run python hw/scripts/fetch_part.py C31966 [C970725 ...]
Run from the repo root or from hw/. Uses atopile's own EasyEDA importer, so the
result is identical to `ato create part`, minus the (login-gated) search step.
"""
import sys
from pathlib import Path

HW = Path(__file__).resolve().parents[1]

def main(ids: list[str]) -> None:
    from atopile.config import config
    config.apply_options(None, working_dir=HW)
    # atopile 0.15 asks its (login-gated) backend only for the manufacturer name;
    # stub that out so the EasyEDA fetch itself works without an account.
    import faebryk.libs.picker.api.api as _api
    class _NoBackend:
        def fetch_part_by_lcsc(self, *_a, **_k): return []
    _api.get_api_client = lambda: _NoBackend()
    from faebryk.libs.picker.lcsc import download_easyeda_info
    from faebryk.libs.part_lifecycle import PartLifecycle, PartIsNotAutoGenerated
    for lcsc in ids:
        try:
            epart = download_easyeda_info(lcsc, get_model=True)
            apart = PartLifecycle.singleton().library.ingest_part_from_easyeda(epart)
            print(f"{lcsc}: {apart.identifier} -> {apart.path.relative_to(HW)}")
            print("   ", apart.generate_import_statement(config.project.paths.src))
        except PartIsNotAutoGenerated as e:
            print(f"{lcsc}: already exists and was hand-edited, skipping ({e.part.path})")

if __name__ == "__main__":
    main(sys.argv[1:])
