"""Generate the parameter binding and preview wire arrays using the standard library."""
from pathlib import Path
import argparse,json
H=Path(__file__).resolve().parent

def generated():
 p=json.loads((H/'parameters/enclosure-v2.json').read_text());c=p['case'];b=p['buttons'];values={'v2_case_width':c['width'],'v2_case_height':c['height'],'v2_case_depth':c['depth'],'v2_case_bottom':c['bottom_y'],'v2_button_x':b['x'],'v2_button_ys':b['ys'],'v2_button_fastener_x':b['guide_fastener_x'],'v2_controller_rear_x':p['board_pose']['rear_x']}
 params='// Generated by prepare.py from the versioned interface contract.\n'+''.join(k+'='+json.dumps(v,separators=(',',':'))+';\n'for k,v in values.items())
 m=json.loads((H/'data/motor-service.json').read_text());e=json.loads((H/'data/encoder-parking.json').read_text());r=json.loads((H/'data/routes.json').read_text());pack=json.loads((H/'data/pack-paths.json').read_text())
 arrays={'pack_paths':pack[1],'motor_paths':[r['paths']['motor1'],r['paths']['motor2']],'signal_paths':[r['paths']['encoder'],r['paths']['home']],'motor_fixed_paths':[v['path']for v in m['cases'][0]],'encoder_complete_path':m['encoder_cases'][0]['path'],'parked_motor_paths':[v['path']for v in m['motor_parking_cases'][-1]],'parked_encoder_path':e['cases'][-1]['path']}
 wires='// Generated nominal preview paths. All three pack-row cases remain in data.\n'+''.join(k+'='+json.dumps(v,separators=(',',':'))+';\n'for k,v in arrays.items())
 return {'source/parameters.scad':params,'source/wire_arrays.scad':wires}

def main():
 a=argparse.ArgumentParser();a.add_argument('--check',action='store_true');args=a.parse_args()
 for name,text in generated().items():
  p=H/name
  if args.check:assert p.read_text()==text,name+' is stale'
  else:p.write_text(text)
 print('Generated parameter/wire sources '+('match'if args.check else'updated'))
if __name__=='__main__':main()
