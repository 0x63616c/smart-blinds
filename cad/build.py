HERE = Path(__file__).resolve().parent
SOURCE = HERE / 'source' / 'smart_blinds.scad'
CONFIG = HERE / 'parameters' / 'packaging.json'
PARTS = ['base', 'cover', 'cradle', 'clamp', 'wheel', 'guard', 'pcb_tray', 'button', 'coupons']


def parameters(data):
    c,m,ch,p,s=data['cell'],data['motor'],data['chain'],data['pcb'],data['shell']
    values = dict(cell_d=c['diameter_max'],cell_l=c['length_max'],pack_d=c['insulated_envelope_diameter'],pack_l=c['insulated_envelope_length'],cell_pitch=c['pitch'],
        motor_d=m['body_diameter'],motor_l=m['body_length'],shaft_d=m['shaft_diameter'],shaft_l=m['shaft_length'],shaft_flat=m['shaft_across_flat'],
        chain_pitch=ch['pitch'],chain_bead=ch['bead_diameter'],chain_link=ch['link_max'],chain_pockets=ch['pockets'],chain_clearance=ch['pocket_clearance'],wheel_width=ch['wheel_width'],
        pcb_width=p['width'],pcb_height=p['height'],pcb_thickness=p['thickness'],pcb_component_h=p['component_height_allowance'],antenna_w=p['antenna_clear_width'],
        shell_wall=s['wall'],shell_base=s['base'],shell_radius=s['corner_radius'])
    for target,key in [('option_sizes','outer'),('pack_origins','pack_origin'),('motor_origins','motor_origin'),('pcb_origins','pcb_origin'),('cell_cols','cell_columns'),('cell_depth','cell_depth_layers'),('cell_rows','cell_vertical_rows')]:
        values[target]=[o[key] for o in data['options']]
    return '// GENERATED by cad/build.py from cad/parameters/packaging.json. Do not edit.\n'+'\n'.join(f'{k} = {json.dumps(v)};' for k,v in values.items())+'\n'


def metrics(data):
    rows=[]
    for opt in data['options']:
        w,h,d=opt['outer']; c=data['cell']; p=data['pcb']; o=opt['pack_origin']; b=opt['pcb_origin']
        if opt['id']!='narrow':
            pack_box=[o[0]-c['insulated_envelope_diameter']/2,o[1],o[2]-c['insulated_envelope_diameter']/2,
                      o[0]+(opt['cell_columns']-1)*c['pitch']+c['insulated_envelope_diameter']/2,o[1]+opt['cell_vertical_rows']*c['insulated_envelope_length']+(opt['cell_vertical_rows']-1)*4,o[2]+(opt['cell_depth_layers']-1)*c['pitch']+c['insulated_envelope_diameter']/2]
        else:
            pack_box=[o[0],o[1]-c['insulated_envelope_diameter']/2,o[2]-c['insulated_envelope_diameter']/2,
                      o[0]+c['insulated_envelope_length'],o[1]+2*c['pitch']+c['insulated_envelope_diameter']/2,o[2]+c['pitch']+c['insulated_envelope_diameter']/2]
        inner=[data['shell']['wall'],data['shell']['wall'],data['shell']['base'],w-data['shell']['wall'],h-data['shell']['wall'],d-data['shell']['wall']]
        pack_margins=[round(pack_box[i]-inner[i],3) for i in range(3)]+[round(inner[i+3]-pack_box[i+3],3) for i in range(3)]
        pcb_front_gap=d-data['shell']['wall']-(b[2]+p['thickness']+p['component_height_allowance'])
        rows.append(dict(id=opt['id'],name=opt['name'],outer_mm=opt['outer'],bounding_volume_cm3=round(w*h*d/1000,1),wall_area_cm2=round(w*h/100,1),depth_mm=d,
                         pack_envelope_bounds_mm=pack_box,pack_to_inner_shell_bounds_mm=pack_margins,pcb_front_gap_mm=round(pcb_front_gap,3),
                         passes_axis_aligned_envelope_checks=min(pack_margins)>=0 and pcb_front_gap>=0,
                         limits='Bounding-box checks only; rounded corners, purchased-part geometry, wiring bends, full assembly collisions, loads and thermal/RF performance require further validation.'))
        if opt['id']!='narrow':
            row=rows[-1]
            row['shaft_offset_sensitivity']=[dict(offset_y_mm=dy,offset_z_mm=dz,
                wheel_rear_margin_mm=round(opt['motor_origin'][2]+dz-15-data['shell']['base'],2),
                wheel_front_margin_mm=round(d-data['shell']['wall']-(opt['motor_origin'][2]+dz+15),2),
                wheel_top_margin_mm=round(h-data['shell']['wall']-(opt['motor_origin'][1]+dy+15),2))
                for dy in (-7,0,7) for dz in (-7,0,7)]
            row['offset_note']='Sensitivity of 30mm flange envelope only. Scenarios are not measured limits; retune guard and ports after measurement.'
    c=next(x for x in rows if x['id']=='compact'); opt=next(x for x in data['options'] if x['id']=='compact')
    c['antenna_lateral_pack_gap_mm']=round(opt['pcb_origin'][0]+data['pcb']['width']-data['pcb']['antenna_clear_width']-c['pack_envelope_bounds_mm'][3],3)
    return {'revision':data['revision'],'status':'geometric packaging study; not physical acceptance','options':rows,
        'drive':{'pocket_count':data['chain']['pockets'],'pitch_radius_mm':round(data['chain']['pitch']/(2*math.sin(math.pi/data['chain']['pockets'])),3),
                 'nominal_chain_speed_mm_per_s_at_111_rpm':round(data['chain']['pockets']*data['chain']['pitch']*111/60,2),
                 'torque_Nm_at_22_24_N_pull':round(22.24*data['chain']['pitch']/(2*math.sin(math.pi/data['chain']['pockets']))/1000,3),
                 'limits':'Ideal kinematics; no efficiency, acceleration, wear, shaft load or slip allowance. Use encoder control and measure torque; 111RPM is listing speed, not guaranteed loaded speed.'}}


def write_footprints(data, destination):
    from html import escape
    scale=2.3; left=40; baseline=650
    parts=['<svg xmlns="http://www.w3.org/2000/svg" width="1400" height="840" viewBox="0 0 1400 840">',
      '<rect width="1400" height="840" fill="#f4f3ef"/>',
      '<style>text{font-family:system-ui,sans-serif;fill:#222827}.name{font-size:24px;font-weight:650}.dim{font-size:18px}.note{font-size:17px;fill:#626965}</style>',
      '<text x="40" y="48" font-size="30" font-weight="650">Four ways to package the same six cells and motor</text>',
      '<text x="40" y="80" class="note">Front footprints at the same scale. Original parametric study; not a measured or released enclosure.</text>']
    for option in data['options']:
        w,h,d=option['outer']; width=w*scale; height=h*scale; top=baseline-height
        parts.append(f'<rect x="{left}" y="{top}" width="{width}" height="{height}" rx="20" fill="#fff" stroke="#aab1ac" stroke-width="2"/>')
        for dx in (-12,12):
            parts.append(f'<circle cx="{left+(w/2+dx)*scale}" cy="{baseline-27*scale}" r="11.5" fill="#d9ddd7"/>')
        parts.append(f'<text x="{left}" y="{baseline+38}" class="name">{escape({"broad":"Broad / shallow", "compact":"Compact / direct", "narrow":"Narrow / bevel", "slim":"Slim / direct"}[option["id"]])}</text>')
        parts.append(f'<text x="{left}" y="{baseline+67}" class="dim">{w} × {h} × {d} mm</text>')
        parts.append(f'<text x="{left}" y="{baseline+95}" class="note">{d} mm from the wall</text>')
        left += width+43
    parts.append('<text x="40" y="805" class="note">Compact direct drive is the initial candidate. Slim direct drive trades height for less wall projection. Motor, pack and RF fit remain provisional.</text></svg>')
    destination.write_text(''.join(parts))


def run_scad(binary, output, option, part, render=False):
    cmd=[binary,'-o',str(output),'-D',f'option="{option}"','-D',f'part="{part}"']
    if render:
        cmd += ['--preview','--imgsize=1400,1400','--camera=0,0,0,20,0,25,500','--autocenter','--viewall','--projection=o','--colorscheme=Tomorrow']
    else:
        cmd += ['--export-format=binstl']
    cmd += [str(SOURCE)]
    result=subprocess.run(cmd,text=True,stdout=subprocess.PIPE,stderr=subprocess.STDOUT)
    print(f'{option}/{part}: {result.stdout.strip()[-600:]}',flush=True)
    if result.returncode or not output.exists() or output.stat().st_size==0 or 'ERROR:' in result.stdout:
        raise RuntimeError(f'OpenSCAD failed: {cmd}\n{result.stdout}')


def inspect_stl(path):
    raw=path.read_bytes(); n=struct.unpack_from('<I',raw,80)[0]
    if len(raw)!=84+50*n: raise ValueError(f'Unexpected binary STL size: {path}')
    parents={}
    def find(v):
        parents.setdefault(v,v)
        while parents[v]!=v:
            parents[v]=parents[parents[v]];v=parents[v]
        return v
    def union(a,b):
        a,b=find(a),find(b)
        if a!=b: parents[b]=a
    edges={}; mins=[math.inf]*3; maxs=[-math.inf]*3; volume=0.0
    for i in range(n):
        vals=struct.unpack_from('<12fH',raw,84+50*i); vertices=[tuple(round(v,5) for v in vals[j:j+3]) for j in (3,6,9)]
        a,b,c=vertices
        union(a,b);union(b,c)
        volume += (a[0]*(b[1]*c[2]-b[2]*c[1])+a[1]*(b[2]*c[0]-b[0]*c[2])+a[2]*(b[0]*c[1]-b[1]*c[0]))/6
        for vertex in vertices:
            for j in range(3): mins[j]=min(mins[j],vertex[j]); maxs[j]=max(maxs[j],vertex[j])
        for j in range(3):
            edge=tuple(sorted((vertices[j],vertices[(j+1)%3])));edges[edge]=edges.get(edge,0)+1
    non_manifold=sum(v!=2 for v in edges.values())
    return dict(file=path.relative_to(HERE).as_posix(),triangles=n,bounds_mm=[mins,maxs],volume_cm3=round(abs(volume)/1000,3),non_manifold_edges=non_manifold,closed_edge_mesh=non_manifold==0,connected_shells=len({find(v) for v in parents}),
                note='Mesh topology check only; not strength, slicer, fit or functional acceptance.')


def main():
    parser=argparse.ArgumentParser(); parser.add_argument('--parameters-only',action='store_true');parser.add_argument('--check-parameters',action='store_true');parser.add_argument('--render',action='store_true');parser.add_argument('--export',action='store_true');parser.add_argument('--openscad',default=os.environ.get('OPENSCAD','openscad')); args=parser.parse_args()
    config_bytes=CONFIG.read_bytes(); data=json.loads(config_bytes); expected=parameters(data); target=HERE/'source'/'parameters.scad'
    if args.check_parameters:
        if not target.exists() or target.read_text()!=expected: raise SystemExit('Generated parameters are stale; run python3 cad/build.py --parameters-only')
        print('Generated parameters match the source JSON.');return
    target.write_text(expected)
    if args.parameters_only:return
    input_paths=(CONFIG,SOURCE,target,Path(__file__).resolve())
    source_snapshot={p.relative_to(HERE).as_posix():hashlib.sha256(p.read_bytes()).hexdigest() for p in input_paths}
    if source_snapshot[CONFIG.relative_to(HERE).as_posix()]!=hashlib.sha256(config_bytes).hexdigest():
        raise RuntimeError('Parameters changed during generation; rerun from a stable source tree.')
    gen=HERE/'generated';gen.mkdir(exist_ok=True)
    evidence=metrics(data)
    write_footprints(data,gen/'footprints.svg')
    if args.render or args.export:
        binary=shutil.which(args.openscad) or args.openscad
        if args.render:
            for option in ('broad','compact','narrow','slim'):
                run_scad(binary,gen/f'{option}-assembly.png',option,'assembly',True)
            for part in ('closed','exploded'):
                run_scad(binary,gen/f'compact-{part}.png','compact',part,True)
        if args.export:
            dest=HERE/'exports'/'provisional';dest.mkdir(parents=True,exist_ok=True)
            evidence['meshes']=[]
            for part in PARTS:
                file=dest/f'{part}.stl';run_scad(binary,file,'compact',part);evidence['meshes'].append(inspect_stl(file))
            if not all(m['closed_edge_mesh'] for m in evidence['meshes']): raise RuntimeError('Non-manifold exported mesh; inspect evidence')
            if not all(m['connected_shells']==1 for m in evidence['meshes'] if not m['file'].endswith('/coupons.stl')): raise RuntimeError('Disconnected single-part mesh; inspect evidence')
            coupon=next(m for m in evidence['meshes'] if m['file'].endswith('/coupons.stl'))
            if coupon['connected_shells']!=8: raise RuntimeError('Coupon sheet must contain eight separate printable objects.')
    final_snapshot={p.relative_to(HERE).as_posix():hashlib.sha256(p.read_bytes()).hexdigest() for p in input_paths}
    if final_snapshot!=source_snapshot:
        raise RuntimeError('Source files changed while CAD ran. Evidence was not published; rerun from a stable source tree.')
    evidence['source_sha256']=source_snapshot
    evidence['source_snapshot_verified_unchanged']=True
    staged=gen/'verification.json.tmp'
    staged.write_text(json.dumps(evidence,indent=2)+'\n'); staged.replace(gen/'verification.json')
    print(f"Verified {len(evidence['options'])} packaging options and {len(evidence.get('meshes', []))} meshes against unchanged source inputs.")

if __name__=='__main__': main()
