#!/usr/bin/env python3
"""Reproduce the holder/drive comparison; standard library only."""
import argparse, hashlib, json, math, subprocess
from pathlib import Path
from html import escape
ROOT=Path(__file__).resolve().parent
CONFIG=ROOT/'parameters/packaging-v2.json'
SOURCE=ROOT/'source/packaging_v2.scad'
INCLUDE=ROOT/'source/packaging_v2_parameters.scad'

def generated(d):
    keys={'ids':'id','sizes':'outer','batteries':'battery','drives':'drive','pcbs':'pcb','motors':'motor','carriers':'carrier','radios':'radio'}
    return '// GENERATED by cad/build_v2.py; edit packaging-v2.json.\n'+'\n'.join(k+'='+json.dumps([o.get(v,[0,0,0,0,0]) for o in d['options']])+';' for k,v in keys.items())+'\n'

def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()

def bounds(d,o):
    if o['battery']=='welded':return [[6.5,10,5.5,76.5,86,52]]
    x,y,z,w,h=o['carrier'];extent=d['holder']['loaded_height_allowance']
    if o['battery']=='broad':return [[x,y,z,x+w,y+h,z+1.6+extent]]
    if o['battery']=='stack':return [[x,y,z-extent,x+w,y+h,z+15.2+extent]]
    return [[x,y,z-extent,x+w,y+h,z+1.6+extent]]

def box_gap(a,b):
    delta=[max(a[i]-b[i+3],b[i]-a[i+3],0) for i in range(3)]
    return round(math.sqrt(sum(x*x for x in delta)),3)

def evidence(d):
    out=[]
    for o in d['options']:
        w,h,z=o['outer'];p=o['pcb'];r=o['radio'];bb=bounds(d,o);rb=r[:3]+[r[i]+r[i+3] for i in range(3)]
        margins=[v for b in bb for v in [b[0]-2.4,b[1]-2.4,b[2]-3,w-2.4-b[3],h-2.4-b[4],z-2.4-b[5]]]
        row={'id':o['id'],'outer_mm':o['outer'],'volume_cm3':round(w*h*z/1000,1),'wall_cm2':round(w*h/100,1),'battery_bounds_mm':bb,'minimum_battery_to_shell_aabb_mm':round(min(margins),3),'pcb_front_margin_mm':round(z-2.4-p[2]-1.6-8,3),'radio_to_battery_envelope_gap_mm':min(box_gap(b,rb) for b in bb),'status':'Bounding reservations only; no detailed collisions, RF performance, current qualification or functional parts claimed.'}
        if 'unrestricted_outer' in o:row['unrestricted_motor_orientation_outer_mm']=o['unrestricted_outer']
        row['aabb_reservations_pass']=min(margins)>=0 and row['pcb_front_margin_mm']>=0 and row['radio_to_battery_envelope_gap_mm']>=15
        if o['battery']=='stack':row['opposing_tail_clearance_before_barrier_mm']=12-2*d['holder']['th_tail_max'];row['barrier_mm']=1;row['tail_status']='12mm clear gap minus two4.5mm maximum tails and1mm barrier leaves2mm total clearance; assembly inspection still required.'
        out.append(row)
    return {'revision':d['revision'],'options':out,'limitations':['RF separation is from conducting internal envelopes only; plastic housing and installed antenna require testing.','Clocked motor assumes eccentric offset directed in Z. Family size is an allowance, not a guaranteed motor specification.','Holder contact current and mechanical insertion retention are not qualified.','No new printable complete enclosure claimed; earlier compact meshes remain fit studies only.']}

def svg(d,p):
    scale=1.23;gap=22;left=30;baseline=355
    width=sum(o['outer'][0]*scale+gap for o in d['options'])+40
    s=[f'<svg xmlns="http://www.w3.org/2000/svg" width="{width:.0f}" height="470" viewBox="0 0 {width:.0f} 470"><rect width="100%" height="100%" fill="#f4f3ef"/><style>text{{font-family:system-ui;fill:#202824}}.dim{{font-size:13px}}.name{{font-size:14px;font-weight:600}}</style><text x="30" y="32" font-size="24">Holders, assembly effort and a supported chain shaft</text><text x="30" y="56" class="dim">Same-scale footprints. Provisional dimensions include clocked eccentric-motor allowance; no physical fit qualification.</text>']
    for o in d['options']:
        w,h,z=o['outer'];x=left;y=baseline-h*scale
        s.append(f'<rect x="{x}" y="{y}" width="{w*scale}" height="{h*scale}" rx="10" fill="white" stroke="#9ca7a0"/>')
        for dy in (27,51):s.append(f'<circle cx="{x+(w-25)*scale}" cy="{baseline-dy*scale}" r="5" fill="#d9ddd7"/>')
        s.append(f'<text x="{x}" y="382" class="name">{escape(o["label"])}</text><text x="{x}" y="405" class="dim">{w} × {h} × {z} mm</text><text x="{x}" y="425" class="dim">{w*h*z/1e6:.2f} litres</text>');left+=w*scale+gap
    s.append('</svg>');p.write_text(''.join(s))

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--parameters-only',action='store_true');ap.add_argument('--check-parameters',action='store_true');ap.add_argument('--render',action='store_true');a=ap.parse_args()
    raw=CONFIG.read_bytes();d=json.loads(raw);expected=generated(d)
    if a.check_parameters:
        if INCLUDE.read_text()!=expected:raise SystemExit('Stale v2 generated parameters')
        print('V2 parameters match.');return
    INCLUDE.write_text(expected)
    if a.parameters_only:return
    paths=[CONFIG,SOURCE,INCLUDE,Path(__file__).resolve()];snapshot={str(p.relative_to(ROOT)):sha(p) for p in paths}
    if snapshot[str(CONFIG.relative_to(ROOT))]!=hashlib.sha256(raw).hexdigest():raise RuntimeError('Config changed while read')
    gen=ROOT/'generated';gen.mkdir(exist_ok=True);ev=evidence(d);svg(d,gen/'holder-footprints.svg')
    if not all(r['aabb_reservations_pass'] for r in ev['options']):raise RuntimeError(json.dumps(ev,indent=2))
    if a.render:
        for o in d['options']:
            parts=['assembly','closed','exploded'] if o['id']=='holders_broad' else ['assembly']
            for part in parts:
                dest=gen/f'{o["id"]}-{part}-v2.png'
                result=subprocess.run(['openscad','-o',str(dest),'--preview','--imgsize=1500,1500','--camera=0,0,0,20,0,25,500','--autocenter','--viewall','--projection=o','--colorscheme=Tomorrow','-D',f'option="{o["id"]}"','-D',f'part="{part}"',str(SOURCE)],capture_output=True,text=True)
                if result.returncode or 'ERROR:' in result.stderr or not dest.exists():raise RuntimeError(result.stderr)
                print(f'{o["id"]}/{part} rendered',flush=True)
    if snapshot!={str(p.relative_to(ROOT)):sha(p) for p in paths}:raise RuntimeError('Inputs changed; evidence not published')
    ev['source_sha256']=snapshot;ev['source_snapshot_verified_unchanged']=True
    tmp=gen/'holder-verification.json.tmp';tmp.write_text(json.dumps(ev,indent=2)+'\n');tmp.replace(gen/'holder-verification.json')
    print('Verified6 packaging reservations; not a physical or collision qualification.')
if __name__=='__main__':main()
